// tokens.json + components.css → boards/tri.css. Edit the sources, not the output.
// TRI_CSS_OUT overrides the output file; TRI_FONTS the font directory the stylesheet points at (default ../fonts/).
const fs = require('fs'); const path = require('path');
const D = __dirname;
const t = JSON.parse(fs.readFileSync(path.join(D, 'tokens.json'), 'utf8'));
const comps = fs.readFileSync(path.join(D, 'components.css'), 'utf8');
const [first, ...later] = t.color.themes.map((th) => th.id);
const val = (tok, th) => (typeof tok.value === 'string' ? (th === first ? tok.value : null) : tok.value[th] ?? null);
const themed = (th) => [...t.color.tokens, ...t.shadow.tokens].map((k) => [k.name, val(k, th)]).filter(([, v]) => v).map(([n, v]) => `  --${n}: ${v};`);
const plain = Object.entries(t).filter(([k, f]) => f && Array.isArray(f.tokens) && !['color', 'shadow'].includes(k)).flatMap(([, f]) => f.tokens.map((k) => `  --${k.name}: ${k.value};`));
const fams = Object.entries(t.type.families).map(([k, v]) => `  --font-${k}: ${v};`);
const typeClasses = t.type.groups.flatMap((g) => g.styles.map((s) => `.${s.name} { font-family: var(--font-${s.family || g.family}); font-size: ${s.fontSize}; line-height: ${s.lineHeight}; font-weight: ${s.fontWeight}; letter-spacing: ${s.letterSpacing}; }`)).join('\n');
const fontDir = process.env.TRI_FONTS || '../fonts/';
const faces = t.type.fonts.map((f) => `@font-face { font-family: "${f.family}"; src: url("${fontDir}${f.file.replace(/^fonts\//, '')}") format("woff2"); font-weight: ${f.weight}; font-style: ${f.style}; font-display: swap;${f.family === 'Archivo' ? ' font-stretch: 62% 125%;' : ''} }`).join('\n');
const small = t.type.groups.flatMap((g) => g.styles).filter((s) => parseFloat(s.fontSize) < 12);
if (small.length) throw new Error('type under 12px: ' + small.map((s) => s.name).join(', '));
const root = '.ao';
const css = [`/* Agent Orrery Tricolor: generated by design/tricolor/build.cjs from tokens.json + components.css. Edit those, not this. */`, faces,
  `${root}, ${root}[data-theme="${first}"] {\n${[...themed(first), ...plain, ...fams].join('\n')}\n}`,
  ...later.map((th) => `${root}[data-theme="${th}"] {\n${themed(th).join('\n')}\n}`), typeClasses, comps].join('\n');
const out = process.env.TRI_CSS_OUT || path.join(D, 'boards', 'tri.css');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, css);
console.log('wrote', path.relative(process.cwd(), out));
