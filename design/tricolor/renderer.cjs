// tokens.json → src/renderer/styles/tokens.css: the @font-face rules, every token as a custom property on :root,
// and one class per type style. Run after editing tokens.json; the renderer never edits tokens.css by hand.
const fs = require('fs'); const path = require('path');
const D = __dirname; const R = path.join(D, '..', '..');
const t = JSON.parse(fs.readFileSync(path.join(D, 'tokens.json'), 'utf8'));
const theme = t.color.themes[0].id;
const val = (tok) => (typeof tok.value === 'string' ? tok.value : tok.value[theme]);
const vars = [
  ...t.color.tokens.map((k) => `  --${k.name}: ${val(k)};`),
  ...t.shadow.tokens.map((k) => `  --${k.name}: ${val(k)};`),
  ...Object.entries(t).filter(([k, f]) => f && Array.isArray(f.tokens) && !['color', 'shadow'].includes(k)).flatMap(([, f]) => f.tokens.map((k) => `  --${k.name}: ${k.value};`)),
  ...Object.entries(t.type.families).map(([k, v]) => `  --font-${k}: ${v};`),
];
const faces = t.type.fonts.map((f) => `@font-face { font-family: "${f.family}"; src: url("../fonts/${f.file.replace(/^fonts\//, '')}") format("woff2"); font-weight: ${f.weight}; font-style: ${f.style}; font-display: swap;${f.family === 'Archivo' ? ' font-stretch: 62% 125%;' : ''} }`);
const styles = t.type.groups.flatMap((g) => g.styles.map((s) => `.t-${s.name} { font-family: var(--font-${s.family || g.family}); font-size: ${s.fontSize}; line-height: ${s.lineHeight}; font-weight: ${s.fontWeight}; letter-spacing: ${s.letterSpacing}; }`));
const small = t.type.groups.flatMap((g) => g.styles).filter((s) => parseFloat(s.fontSize) < 12);
if (small.length) throw new Error('type under 12px: ' + small.map((s) => s.name).join(', '));
const css = [
  `/* tokens.css — Tricolor design tokens. Generated by design/tricolor/renderer.cjs from design/tricolor/tokens.json; edit that, not this. */`,
  ...faces, '', `:root {`, ...vars, `}`, '', `/* type styles: .t-<name>, one per style in tokens.json */`, ...styles, '',
].join('\n');
const out = path.join(R, 'src', 'renderer', 'styles', 'tokens.css');
fs.writeFileSync(out, css);
console.log('wrote', path.relative(R, out), `(${vars.length} tokens, ${styles.length} type styles)`);
